def _ollama_text(prompt):
    payload = json.dumps({
        "model": OLLAMA_MODEL,
        "prompt": SYSTEM + "\n\nStory so far:\n" + prompt,
        "stream": False,
        "options": {"temperature": 0.8},
    }).encode()
    req = urllib.request.Request(
        OLLAMA_BASE + "/api/generate", data=payload,
        headers={"Content-Type": "application/json"})
    try:
        with urllib.request.urlopen(req, timeout=180) as resp:
            data = json.load(resp)
    except Exception:
        return None
    return (data.get("response") or "").strip()


def _openrouter_text(prompt):
    payload = json.dumps({
        "model": OPENROUTER_MODEL,
        "messages": [{"role": "user",
                      "content": SYSTEM + "\n\nStory so far:\n" + prompt}],
        "temperature": 0.8,
    }).encode()
    req = urllib.request.Request(
        OPENROUTER_BASE + "/chat/completions", data=payload,
        headers={"Content-Type": "application/json",
                 "Authorization": "Bearer " + OPENROUTER_API_KEY})
    try:
        with urllib.request.urlopen(req, timeout=180) as resp:
            data = json.load(resp)
    except Exception:
        return None
    try:
        return (data["choices"][0]["message"]["content"] or "").strip()
    except (KeyError, IndexError, TypeError):
        return None


def call_model(prompt):
    """Ask Gemma for one JSON room. Returns dict or None on any failure."""
    if OPENROUTER_API_KEY:
        raw = _openrouter_text(prompt)
    else:
        raw = _ollama_text(prompt)
    if not raw:
        return None
    try:
        room = json.loads(raw)
    except ValueError:
        start, end = raw.find("{"), raw.rfind("}")
        if start < 0 or end <= start:
            return None
        try:
            room = json.loads(raw[start:end + 1])
        except ValueError:
            return None
    if not isinstance(room, dict) or "description" not in room:
        return None
    choices = [c for c in (room.get("choices") or [])
               if isinstance(c, dict)]
    labels = [str(c.get("label", "")).strip().lower() for c in choices]
    if len(choices) < 3 or len(set(labels)) < 3:
        return None
    if any(l in ("short choice text", "choice", "option", "",
                 "open the cellar door", "climb the stairs",
                 "hide in the pantry") for l in labels):
        return None
    room["choices"] = [
        {"label": str(c.get("label", "Go on"))[:80],
         "hint": str(c.get("hint", ""))[:120]}
        for c in choices[:3]
    ]
    room["whisper"] = str(room.get("whisper", ""))[:160]
    room["description"] = str(room["description"])[:900]
    return room


def fallback_room(index):
    room = dict(FALLBACK_ROOMS[index % len(FALLBACK_ROOMS)])
    room["choices"] = [dict(c) for c in room["choices"]]
    return room


def next_room(history, choice_label):
    """Return (room_dict, source) for the next step of the run."""
    step = len(history)
    if step >= ROOMS_PER_RUN:
        return {"description": FALLBACK_ENDING, "choices": [],
                "whisper": "The house is quiet now."}, "fallback"
    prompt = "You are in a haunted house.\n"
    for i, h in enumerate(history):
        prompt += f"Room {i + 1}: {h.get('description', '')}\n"
    if choice_label:
        prompt += f"You chose: {choice_label}\n"
    prompt += "Write the next room."
    room = call_model(prompt)
    if room is not None:
        return room, "gemma"
    return fallback_room(step), "fallback"


def ending(history):
    prompt = "You are in a haunted house.\n"
    for i, h in enumerate(history):
        prompt += f"Room {i + 1}: {h.get('description', '')}\n"
    prompt += ("You have found the way out. Write the escape ending: "
               "3-5 sentences, second person, spooky but hopeful. "
               "Return ONLY JSON: {\"description\": \"...\"}.")
    room = call_model(prompt)
    if room is not None:
        return room["description"], "gemma"
    return FALLBACK_ENDING, "fallback"


class Handler(SimpleHTTPRequestHandler):
    def do_GET(self):
        if self.path in ("/", "/index.html"):
            self.path = "/index.html"
        return SimpleHTTPRequestHandler.do_GET(self)

    def do_POST(self):
        length = int(self.headers.get("Content-Length", 0))
        body = json.loads(self.rfile.read(length) or b"{}")
        if self.path == "/api/room":
            room, source = next_room(body.get("history", []),
                                     body.get("choice", ""))
            out = dict(room)
            out["source"] = source
            out["step"] = len(body.get("history", [])) + 1
            out["total"] = ROOMS_PER_RUN
        elif self.path == "/api/ending":
            text, source = ending(body.get("history", []))
            out = {"description": text, "source": source}
        else:
            self.send_response(404)
            self.end_headers()
            return
        data = json.dumps(out).encode()
        self.send_response(200)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(data)))
        self.end_headers()
        self.wfile.write(data)

    def log_message(self, *args):
        pass


