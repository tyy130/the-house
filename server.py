"""Haunted House — a tiny interactive fiction game for Hacktoberfest Week 4.

Architecture (deliberately boring):
- This file is the whole server: Python standard library only, no pip deps.
- Game state lives in the browser. The server is stateless: each request
  carries the room history, and the server returns the next room.
- Rooms are generated by an open-weight model (Gemma) through a local
  Ollama server. If the model is unreachable or its output is unusable,
  a seeded template room is returned instead and labelled as such, so the
  game never dead-ends. Model proposes, code disposes.

Run:
  ollama serve            # in one terminal
  ollama create gemma3-1b-local -f Modelfile  # first time only (see ~/workspace/ollama)
  OLLAMA_MODEL=gemma3-1b-local python3 server.py
  open http://localhost:8080
"""

